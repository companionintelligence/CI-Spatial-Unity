using System.Collections.Generic;
using System.IO;
using System.Security;
using System.Text;
using System.Xml;
using CompanionScan.Core;
using UnityEditor;
using UnityEditor.Android;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace CompanionScan.Editor
{
    /// <summary>
    /// Generates the Android network security config for every Android build.
    ///
    /// HTTPS is the default: the base config forbids cleartext traffic. Development
    /// builds additionally allow plain http to the LAN hosts listed in
    /// <see cref="ServerConfig.developmentCleartextHosts"/> (validated by
    /// <see cref="CleartextHostPolicy"/>); release builds never allow cleartext.
    ///
    /// The file is written into the Gradle project as
    /// <c>res/xml/companion_network_security_config.xml</c> and referenced from the
    /// application element of the Unity library manifest (see
    /// Assets/Plugins/Android/AndroidManifest.xml), which takes precedence over the
    /// Meta XR SDK's default <c>network_sec_config.xml</c>.
    /// </summary>
    public sealed class AndroidNetworkSecurityConfig : IPreprocessBuildWithReport, IPostGenerateGradleAndroidProject
    {
        public const string ResourceName = "companion_network_security_config";
        public const string ManifestValue = "@xml/" + ResourceName;

        private const string AndroidNamespace = "http://schemas.android.com/apk/res/android";
        private const string ServerConfigAssetPath = "Assets/CompanionScan/Resources/ServerConfig.asset";

        private static bool s_developmentBuild;

        // Run after the Meta XR SDK's OVRGradleGeneration (callbackOrder 99999),
        // which copies its own default config into the Gradle project.
        public int callbackOrder => 100000;

        public void OnPreprocessBuild(BuildReport report)
        {
            s_developmentBuild = report.summary.platform == BuildTarget.Android &&
                                 (report.summary.options & BuildOptions.Development) != 0;
        }

        public void OnPostGenerateGradleAndroidProject(string path)
        {
            var hosts = s_developmentBuild ? LoadDevelopmentCleartextHosts() : new List<string>();

            var xmlDirectory = Path.Combine(path, "src", "main", "res", "xml");
            Directory.CreateDirectory(xmlDirectory);
            File.WriteAllText(Path.Combine(xmlDirectory, ResourceName + ".xml"), BuildXml(hosts), new UTF8Encoding(false));

            SetManifestReference(Path.Combine(path, "src", "main", "AndroidManifest.xml"));

            Debug.Log(hosts.Count == 0
                ? "[NetworkSecurity] HTTPS only: cleartext traffic is disabled in this build."
                : "[NetworkSecurity] Development build: plain http allowed to " + string.Join(", ", hosts) + ".");
        }

        /// <summary>
        /// Network security config XML: cleartext forbidden by default, allowed only
        /// for the valid LAN hosts in <paramref name="cleartextHosts"/>.
        /// </summary>
        public static string BuildXml(IEnumerable<string> cleartextHosts)
        {
            var hosts = CleartextHostPolicy.NormalizeLanHosts(cleartextHosts);

            var xml = new StringBuilder();
            xml.Append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
            xml.Append("<!-- Generated by CompanionScan.Editor.AndroidNetworkSecurityConfig for each build. -->\n");
            xml.Append("<network-security-config>\n");
            xml.Append("  <base-config cleartextTrafficPermitted=\"false\" />\n");
            if (hosts.Count > 0)
            {
                xml.Append("  <domain-config cleartextTrafficPermitted=\"true\">\n");
                foreach (var host in hosts)
                {
                    xml.Append("    <domain includeSubdomains=\"false\">")
                        .Append(SecurityElement.Escape(host))
                        .Append("</domain>\n");
                }

                xml.Append("  </domain-config>\n");
            }

            xml.Append("</network-security-config>\n");
            return xml.ToString();
        }

        /// <summary>Points the manifest's application element at the generated config.</summary>
        public static bool SetManifestReference(string manifestPath)
        {
            if (!File.Exists(manifestPath))
            {
                Debug.LogError("[NetworkSecurity] Android manifest not found: " + manifestPath);
                return false;
            }

            var document = new XmlDocument { PreserveWhitespace = true };
            document.Load(manifestPath);
            if (!(document.SelectSingleNode("/manifest/application") is XmlElement application))
            {
                Debug.LogError("[NetworkSecurity] No <application> element in " + manifestPath);
                return false;
            }

            if (application.GetAttribute("networkSecurityConfig", AndroidNamespace) == ManifestValue)
            {
                return true;
            }

            application.SetAttribute("networkSecurityConfig", AndroidNamespace, ManifestValue);
            var settings = new XmlWriterSettings { Encoding = new UTF8Encoding(false) };
            using (var writer = XmlWriter.Create(manifestPath, settings))
            {
                document.Save(writer);
            }

            return true;
        }

        private static List<string> LoadDevelopmentCleartextHosts()
        {
            var config = AssetDatabase.LoadAssetAtPath<ServerConfig>(ServerConfigAssetPath);
            if (config == null)
            {
                Debug.LogWarning("[NetworkSecurity] " + ServerConfigAssetPath + " not found; cleartext stays disabled.");
                return new List<string>();
            }

            var rejected = new List<KeyValuePair<string, string>>();
            var hosts = CleartextHostPolicy.NormalizeLanHosts(config.developmentCleartextHosts, rejected);
            foreach (var entry in rejected)
            {
                Debug.LogWarning($"[NetworkSecurity] Ignoring development cleartext host \"{entry.Key}\": {entry.Value}.");
            }

            return hosts;
        }
    }
}
